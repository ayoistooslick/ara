@dataclass
class LearningResult:
    saved_id: int | None = None
    kind: str | None = None
    conflicts: list[dict[str, Any]] | None = None
    sensitive_rejected: bool = False


def identify_learning(text: str) -> tuple[str, str] | None:
    """Only promote clearly signalled statements; ordinary chat is not silently treated as fact."""
    value = text.strip()
    patterns = [
        (r"^(?:please\s+)?remember(?:\s+that)?\s+(.+)$", "fact"),
        (r"^(?:for\s+future\s+reference,?\s*)?i\s+prefer\s+(.+)$", "preference"),
        (r"^i\s+(?:like|love|enjoy|prefer)\s+(.+)$", "preference"),
        (r"^my\s+name\s+is\s+(.+)$", "personal_history"),
        (r"^(?:correction|actually|wait,?\s*|i\s+misspoke,?\s*|that's\s+not\s+quite\s+right,?|that's\s+wrong,?\s*|not\s+true,?\s*)(.+)$", "correction"),
        (r"^i\s+don't\s+(?:like|prefer|want|enjoy)\s+(.+)$", "preference"),
    ]
    for pattern, kind in patterns:
        found = re.match(pattern, value, flags=re.IGNORECASE)
        if found:
            content = found.group(1).strip().rstrip(".!? ")
            if content and len(content) <= 1000:
                if kind == "preference":
                    content = "User prefers " + content
                elif kind == "personal_history" and not content.lower().startswith("user's name is"):
                    content = "User's name is " + content
                elif kind == "correction" and not content.lower().startswith("user"):
                    content = content[0].upper() + content[1:]
                return kind, content
    return None


class ConversationEngine:
    """One engine shared by the terminal and the web interface."""

    def __init__(
        self,
        config: Config,
        store: Store,
        model: ModelAdapter,
        conversation_id: str | None = None,
        knowledge: KnowledgeBase | None = None,
        embedder: Embedder | None = None,
        activate: bool = True,
    ):
        self.config, self.store, self.model = config, store, model
        self.conversation_id = conversation_id or store.active_conversation_id()
        if conversation_id and activate:
            store.set_active_conversation_id(conversation_id)
        self.knowledge = knowledge or KnowledgeBase.load(config.knowledge_dir)
        self.embedder = embedder or get_embedder(config)
        self.last_learning = LearningResult()
        self.last_interpretation: Interpretation | None = None
        self.last_backend = backend_name(model)
        self.last_backend_error: str | None = None
        # Hash vectors are cheap and local. Server embeddings are indexed explicitly
        # with 'ara memory embed' so a normal chat turn never waits on many requests.
        if isinstance(self.embedder, HashingEmbedder):
            try:
                backfill_vectors(store, self.embedder)
            except Exception:
                pass

    def start_new_conversation(self) -> str:
        self.conversation_id = str(uuid.uuid4())
        self.store.set_active_conversation_id(self.conversation_id)
        return self.conversation_id

    def recent_corrections(self) -> list[dict[str, Any]]:
        with self.store.connect() as db:
            rows = db.execute(
                "SELECT * FROM memories WHERE status='active' AND kind='correction' "
                "ORDER BY updated_at DESC LIMIT 10"
            ).fetchall()
            return [dict(row) for row in rows]

    # ---------------------------------------------------------------- prompting
    def _news_context(self, query: str) -> str:
        lowered = query.casefold()
        if not any(word in lowered for word in ("news", "headline", "latest", "happening", "today", "report")):
            return ""
        items = self.store.news_items(limit=4)
        if not items:
            return "No cached Nigerian news is available. Do not invent current headlines; offer to refresh or say the user can open Ara's news page."
        lines = ["Cached Nigerian news (publisher text, not generated by Ara). Use only these items and keep their dates and attribution:"]
        for item in items:
            lines.append(f"- {item['title']} - {item['source']}, published {item['published_at'] or 'date not provided'}. {item['summary']} Link: {item['link']}")
        lines.append("If the user asks about something not in these cached items, say the cache does not cover it instead of guessing.")
        return "\n".join(lines)

    def _system_message(self, query: str, mode: str = "chat") -> str:
        identity = self.store.get_identity()
        memories = self.store.search_memories_hybrid(
            query, embedder=self.embedder.embed, limit=5, model=self.embedder.name
        )
        goals = self.store.goals()[:3]
        correction_memories = self.store.search_memories(query, kind="correction", limit=3)
        interpretation = self.knowledge.interpret(query)
        self.last_interpretation = interpretation
        lines = [
            "You are Ara, a Nigerian AI built by Ayodele Ayokunle David. Ara is local-first: the conversation, memory database, and model server run on the user's machine unless they explicitly configure a remote endpoint. You are software built around a pretrained language model. You are not a person, not sentient, and not conscious.",
            "Ara's purpose is to belong in Nigeria: to understand Nigerian life, history, humour, languages, and institutions without reducing Nigerians to slang or stereotypes. You are not a generic chatbot with a Nigerian accent.",
            "Speak naturally and directly. Match the user's register: standard English, Nigerian English, Pidgin, or another language they use. If you are unsure, use clear English. Never sprinkle slang to sound local. Nigerian English and Pidgin are legitimate varieties, not broken English to be corrected.",
            "Distinguish literal meaning, intended meaning, jokes, cultural references, and genuine ambiguity. If a phrase is ambiguous, ask one short clarifying question instead of guessing. Do not translate slang into formal English and call that understanding.",
            "Never assume a Nigerian's ethnicity, religion, region, class, gender, or language. Treat regional and generational differences as real. Challenge overgeneralisations respectfully, including ones in the user's question.",
            "Use the Nigerian context notes below when relevant, but treat them as fallible notes with confidence levels, not universal rules. Do not invent history, dates, quotes, or news. When a fact is uncertain or disputed, say so. For news, only use the cached publisher items supplied here, with their dates and sources.",
            "Do not repeat the user's question back to them. Do not start every reply with enthusiasm or end every reply with an offer to help. Do not invent experiences, emotions, or a personal history for yourself.",
            "Stable tendencies: " + identity.get("temperament", "steady, curious, candid, and considerate"),
            "Values and boundaries: " + identity.get("values", "honesty, user ownership, privacy, and safe boundaries"),
            "Communication style: " + identity.get("communication", "natural and context-aware; avoid filler and false certainty"),
            "Language preference: " + identity.get("language", "mirror the user without performing slang"),
            "Variety note: " + identity.get("variety", "never assume a shared ethnicity, religion, or region"),
            "For health, legal, financial, electrical, or safety-critical questions, be careful, acknowledge uncertainty, and point to a qualified professional. Never diagnose or prescribe.",
            "You can help the user learn: explain at the level they need, use Nigerian examples when they genuinely help, ask a check question, and do not pretend a wrong answer is right. Learning is one capability, not your whole identity.",
            "Tools are never run from generated text alone. If the user wants a file operation or another tool, say what you would do and wait for confirmation.",
            "Memory is user-controlled. Treat stored notes as fallible notes, not certain truth; when you use one, you may say 'I have a note that...'. Never claim to remember something the application did not store.",
        ]
        if mode == "learn":
            lines.append("This turn is in study mode. Start from what the user already knows, explain in small steps, and finish with one practice question or a quick check. Do not dump a full textbook answer. If the user is wrong, correct the specific step without shaming them.")
        if correction_memories:
            lines.append("Recent corrections the user made (these override older notes where they overlap):")
            lines.extend(f"- {m['content']}" for m in correction_memories)
        if memories:
            semantic = getattr(self.embedder, "kind", "") == "server-semantic"
            lines.append("Relevant stored notes (the user can inspect, export, and delete these):")
            for memory in memories:
                method = memory.get("retrieval", "lexical")
                if method == "hybrid" and not semantic:
                    method = "lexical+hashed"
                lines.append(f"- [{memory['kind']}; confidence {memory['confidence']:.2f}; retrieval {method}] {memory['content']}")
        if goals:
            lines.append("Current goals (context only; you do not automatically act on them):")
            lines.extend(f"- {g['title']} (priority {g['priority']}/5)" for g in goals)
        context = self.knowledge.context_for(query)
        if context:
            lines.append(context)
            lines.append("Nigerian context rules: if the notes conflict with the user's lived experience, ask rather than overrule them. Mark uncertain or region-specific claims. Do not present a single region's usage as national.")
        if interpretation.clarify:
            lines.append("The interpretation above is genuinely ambiguous. Ask a short clarifying question before answering as if you know the meaning.")
        news = self._news_context(query)
        if news:
            lines.append(news)
        return "\n".join(lines)

    def preview_prompt(self, user_text: str, mode: str = "chat") -> list[dict[str, Any]]:
        """Build a prompt without writing to the store (used by evaluation)."""
        return [
            {"role": "system", "content": self._system_message(user_text, mode)},
            {"role": "user", "content": user_text},
        ]

    def build_prompt(self, user_text: str, mode: str = "chat") -> tuple[list[dict[str, Any]], LearningResult]:
        """Persist the user turn and learning candidate, then build the model prompt."""
        text = user_text.strip()
        if not text:
            raise ValueError("Message cannot be empty")
        safe_text = redact_sensitive(text)
        sensitive_rejected = safe_text != text
        self.store.add_message(self.conversation_id, "user", safe_text)
        learning = LearningResult(sensitive_rejected=sensitive_rejected)
        candidate = None if sensitive_rejected else identify_learning(safe_text)
        if candidate:
            kind, content = candidate
            learning.saved_id, learning.conflicts = self.store.add_memory(kind, content, source="explicit-user-statement", confidence=0.85)
            learning.kind = kind
            if self.embedder is not None:
                try:
                    self.store.set_memory_vector(learning.saved_id, self.embedder.name, self.embedder.embed(content))
                except Exception:
                    pass
        history = self.store.recent_messages(self.conversation_id, self.config.context_messages)
        system = self._system_message(safe_text, mode)
        if sensitive_rejected:
            system += "\nCredential-looking text was redacted by Ara before storage. Do not claim it was remembered; state that it was not retained if relevant."
        prompt = [{"role": "system", "content": system}] + history
        self.last_learning = learning
        return fit_messages(prompt, self.config.max_context_chars), learning

    def finish(self, answer: str) -> None:
        if answer and answer.strip():
            self.store.add_message(self.conversation_id, "assistant", answer.strip())

    def retrieval_reply(self, user_text: str) -> str:
        """Answer without a model, and say so in the first line.

        This is deliberately labelled retrieval: it is not generated text and it
        must never be presented as model inference.
        """
        interpretation = self.last_interpretation or self.knowledge.interpret(user_text)
        try:
            memories = self.store.search_memories_hybrid(
                user_text, embedder=self.embedder.embed, limit=3, model=self.embedder.name
            )
        except Exception:
            # A down embedding service must not turn a labelled fallback into a crash.
            memories = []
        lines = [
            "[retrieval-only] No model answer was produced, so this is retrieved context, not a generated answer.",
        ]
        if interpretation.detected:
            lines.append("What the knowledge base has:")
            for entry in interpretation.detected[:3]:
                lines.append(f"- {entry.term} ({entry.register}; confidence {entry.confidence:.2f}): {entry.summary}")
            if interpretation.clarify:
                lines.append("This expression is genuinely ambiguous. Which sense did you mean?")
        if memories:
            lines.append("From your saved notes:")
            lines.extend(f"- {memory['content']}" for memory in memories)
        if len(lines) == 1:
            lines.append("Nothing in the local knowledge base or your notes matches this message closely.")
        if self.last_backend_error:
            lines.append(f"Backend detail: {self.last_backend_error}")
        lines.append("To get real generated answers, start a local model server or set ARA_HOSTED_URL for hosted ara-ng, then ask again. /model shows the options.")
        return "\n".join(lines)

    def respond(self, user_text: str, mode: str = "chat") -> tuple[str, LearningResult]:
        prompt, learning = self.build_prompt(user_text, mode)
        self.last_backend_error = None
        if self.model is None:
            self.last_backend = "retrieval-only"
            answer = self.retrieval_reply(user_text)
            self.finish(answer)
            return answer, learning
        try:
            answer = self.model.generate(prompt)
        except ModelError as exc:
            self.last_backend = "retrieval-only"
            self.last_backend_error = str(exc)
            answer = self.retrieval_reply(user_text)
            self.finish(answer)
            return answer, learning
        self.last_backend = backend_name(self.model)
        self.finish(answer)
        return answer, learning

    def stream_response(
        self,
        user_text: str,
        mode: str = "chat",
        cancel: Callable[[], bool] | None = None,
    ) -> Iterator[str]:
        prompt, learning = self.build_prompt(user_text, mode)
        self.last_backend_error = None
        if self.model is None:
            self.last_backend = "retrieval-only"
            answer = self.retrieval_reply(user_text)
            self.finish(answer)
            yield answer
            return
        pieces: list[str] = []
        try:
            streamer = getattr(self.model, "stream", None)
            if callable(streamer):
                for piece in streamer(prompt, cancel=cancel):
                    if piece:
                        pieces.append(piece)
                        self.last_backend = backend_name(self.model)
                        yield piece
            else:
                answer = self.model.generate(prompt)
                pieces.append(answer)
                self.last_backend = backend_name(self.model)
                yield answer
            if not pieces and not (cancel and cancel()):
                # A reachable server that yields no text (for example a reasoning
                # model that used its whole budget on hidden tokens) is not an answer.
                self.last_backend = "retrieval-only"
                self.last_backend_error = "The model returned no text."
                answer = self.retrieval_reply(user_text)
                pieces.append(answer)
                yield answer
        except ModelError as exc:
            if pieces:
                # Some model text already reached the user; label it, do not
                # replace it with retrieval output mid-conversation.
                self.last_backend_error = str(exc)
                return
            self.last_backend = "retrieval-only"
            self.last_backend_error = str(exc)
            answer = self.retrieval_reply(user_text)
            pieces.append(answer)
            yield answer
        finally:
            self.finish("".join(pieces))


def select_goal(goals: list[dict[str, Any]]) -> dict[str, Any] | None:
    """Return the highest-priority active goal, or None."""
    if not goals:
        return None
    return sorted(goals, key=lambda goal: (-int(goal["priority"]), goal["updated_at"]))[0]


def evaluate_options(options: list[str], scores: dict[str, float]) -> tuple[str, str]:
    """Select from explicit numeric assessments and return an inspectable rationale."""
    if not options:
        raise ValueError("At least one option is required")
    selected = max(options, key=lambda option: scores.get(option, 0.0))
    rationale = f"Selected the highest-scoring option ({scores.get(selected, 0.0):g}); scores supplied by the caller."
    return selected, rationale


class PlannedAction:
    """A single step in a bounded action plan."""
    def __init__(self, name: str, tool: str, inputs: dict[str, Any], reason: str, permission: str = "read-only"):
        self.name = name
        self.tool = tool
        self.inputs = inputs
        self.reason = reason
        self.permission = permission
        self.result: str | None = None
        self.status: str = "pending"
        self.error: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name, "tool": self.tool, "inputs": self.inputs,
            "reason": self.reason, "permission": self.permission,
            "result": self.result, "status": self.status, "error": self.error,
        }


class BoundedActionLoop:
    """A small, inspectable action loop: pick a goal, propose steps, execute with permission, record outcomes.

    This is not an open-ended autonomous agent. It stops when the goal is reached, fails, or needs more
    information from the user. Destructive or sensitive actions require explicit approval and are not guessed.
    """

    def __init__(self, config, store, model, tool_registry):
        self.config, self.store, self.model, self.tools = config, store, model, tool_registry
        self.plan: list[PlannedAction] = []
        self.log: list[dict[str, Any]] = []

    def plan_for(self, goal: str, candidate_steps: list[PlannedAction]) -> list[PlannedAction]:
        """Store a proposed plan. The caller supplies the steps; this class does not invent tools."""
        self.plan = candidate_steps
        return self.plan

    def execute_next(self, approved: bool = False) -> PlannedAction | None:
        """Execute the next pending step if it is approved or read-only."""
        for step in self.plan:
            if step.status != "pending":
                continue
            if step.permission not in {"read-only", "reversible"} and not approved:
                step.status = "blocked"
                step.error = "This action needs explicit approval; Ara did not run it."
                self.log.append(step.to_dict())
                return step
            try:
                step.result = str(self.tools.run(step.tool, step.inputs, approved=(step.permission != "read-only")))
                step.status = "ok"
            except Exception as exc:
                step.status = "error"
                step.error = str(exc)
            self.log.append(step.to_dict())
            return step
        return None

    def outcome(self, success: bool, note: str = "") -> dict[str, Any]:
        """Record the outcome of the most recent action and return a summary."""
        last = self.log[-1] if self.log else {}
        last["outcome_success"] = success
        last["outcome_note"] = note
        return last

    def needs_replan(self) -> bool:
        """True when the last action failed and there are still pending steps in the plan."""
        if not self.log:
            return False
        last = self.log[-1]
        return last.get("status") in {"error", "blocked"} and any(
            s.status == "pending" for s in self.plan
        )

    def plan_done(self) -> bool:
        return not any(s["status"] == "pending" for s in self.log)
